#!/usr/bin/env python3
"""Write the book's appendix of all SimulationCode parameters from SimulationCode/PARAMETERS.md (which `./nbody
--parameters PARAMETERS.md` generates from src/ParameterSchema.h), so the appendix never drifts from the code.

    python3 tools/simcode_parameters.py ../FML/SimulationCode/PARAMETERS.md chapters/B_simulationcode_parameters.tex

`make` runs this when PARAMETERS.md is newer than the appendix."""
import re
import sys

SPECIAL = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$', '#': r'\#', '_': r'\_', '{': r'\{',
           '}': r'\}', '~': r'\textasciitilde{}', '^': r'\textasciicircum{}'}


def esc(text):
    return ''.join(SPECIAL.get(c, c) for c in text)


def code(text):
    """Inline code: \\code (nolinkurl, breaks at _) for text without characters it cannot take, else \\texttt"""
    if re.search(r'[%#{}\\]', text):  # \nolinkurl would drop braces
        return r'\texttt{' + esc(text) + '}'
    return r'\code{' + text + '}'


def inline(text):
    """Markdown inline text to LaTeX: `code`, *emphasis*, identifiers with underscores as code (so they break)"""
    out = []
    for i, part in enumerate(re.split(r'`([^`]*)`', text)):
        if i % 2:
            out.append(code(part))
            continue
        for j, sub in enumerate(re.split(r'\*([^*]+)\*', part)):
            if j % 2:
                out.append(r'\emph{' + esc(sub) + '}')
                continue
            for k, tok in enumerate(re.split(r'([A-Za-z0-9.<>/\[\]]*_[A-Za-z0-9_.<>/\[\]]*)', sub)):
                out.append(code(tok) if k % 2 and re.fullmatch(r'[A-Za-z0-9_.<>/\[\]]+', tok) else esc(tok))
    return ''.join(out)


def cells(line):
    return [c.strip() for c in line.strip().strip('|').split('|')]


def main(src, dst):
    lines = open(src, encoding='utf-8').read().split('\n')
    out = [r'% Generated by tools/simcode_parameters.py from FML/SimulationCode/PARAMETERS.md. Do not edit.',
           r'\chapter{SimulationCode parameters}\label{app:simcode-parameters}',
           '',
           r'Every parameter of SimulationCode (\cref{ch:simulation-code}), as the code defines it in \file{src/ParameterSchema.h}'
           r' and \file{SimulationParameters.h}. This appendix is generated from \file{SimulationCode/PARAMETERS.md}, which'
           r' \code{./nbody --parameters PARAMETERS.md} writes, so it lists exactly the parameters, defaults, conditions and'
           r' allowed values of the code. Each entry gives the type and the default value (\emph{required}: no default),'
           r' when the parameter is read, and its meaning.', '']
    i, n_params = 0, 0
    while i < len(lines):
        line = lines[i]
        if line.startswith('## '):
            out.append(r'\section{' + esc(line[3:].strip()) + '}')
            out.append('')
        elif line.startswith('| Parameter | Type | Default | Used when | Description |'):
            out.append(r'{\small\begin{longtable}{@{}>{\raggedright\arraybackslash}p{4.3cm}>{\raggedright\arraybackslash}p{2.8cm}'
                       r'>{\raggedright\arraybackslash}p{8.1cm}@{}}')
            head = r'\toprule Parameter (type, default) & Used when & Description \\ \midrule'
            out += [head, r'\endfirsthead', head, r'\endhead', r'\bottomrule', r'\endlastfoot']
            i += 2
            while i < len(lines) and lines[i].startswith('|'):
                parts = lines[i].strip().strip('|').split('|')  # the description may contain |
                name, typ, default, when = (c.strip() for c in parts[:4])
                desc = '|'.join(parts[4:]).strip()
                name = name.strip('`')
                out.append(r'\param{' + name + r'}\newline{\footnotesize ' + esc(typ) + ', ' + inline(default) + '} & ' +
                           inline(when) + ' & ' + inline(desc) + r' \\[2pt]')
                n_params += 1
                i += 1
            out.append(r'\end{longtable}}')
            out.append('')
            continue
        elif line.startswith('| Needs |'):
            heads = cells(line)
            out.append(r'{\small\begin{longtable}{@{}>{\raggedright\arraybackslash}p{9.0cm}cc@{}}')
            head = r'\toprule ' + ' & '.join(inline(h) for h in heads) + r' \\ \midrule'
            out += [head, r'\endfirsthead', head, r'\endhead', r'\bottomrule', r'\endlastfoot']
            i += 2
            while i < len(lines) and lines[i].startswith('|'):
                out.append(' & '.join(inline(c) for c in cells(lines[i])) + r' \\')
                i += 1
            out.append(r'\end{longtable}}')
            out.append('')
            continue
        elif line.startswith('# ') or line.startswith('Generated with') or line.startswith('Parameters marked'):
            pass
        elif line.strip():
            out.append(inline(line))
            out.append('')
        i += 1
    open(dst, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(f'{dst}: {n_params} parameters')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
