#!/usr/bin/env python3
"""Write EMantisReference.h: predictions of the e-MANTIS Python package (pip install emantis==1.4.0) for
test_emantis.cpp. Usage: python3 make_emantis_reference.py > EMantisReference.h"""

import numpy as np
import sklearn

import emantis
from emantis.exceptions import EmulationRangeError
from emantis.halo_mass_function import HMFEmulator
from emantis.matter_power_spectrum import NonLinearBoostEmulator, NonLinearMGBoostEmulator, Sigma8Emulator

NAN = float("nan")


def arr(v):
    return "{" + ", ".join(repr(float(x)) if np.isfinite(x) else "NAN" for x in np.atleast_1d(v)) + "}"


cases = []  # (kind, model, extra, params dict for the C++ struct, a, flag1, flag2, x, expected, expected_std, error)


def add(kind, model, extra, P, a, f1, f2, x, fn, s8name):
    Q = {k: P.get(k, NAN) for k in ("Omega_b", "Omega_m", "h", "n_s", "A_s", "logfR0")}
    Q["sigma8"] = P.get(s8name, NAN)
    Q["w"] = P.get("w", -1.0)
    try:
        out = fn()
        pred, std = (out if isinstance(out, tuple) else (out, []))
        err = ""
    except EmulationRangeError as e:
        pred, std, err = [], [], e.param
    cases.append((kind, model, extra, Q, a, f1, f2, x, np.atleast_1d(pred), np.atleast_1d(std), err))


fid_fR = {"Omega_b": 0.049, "Omega_m": 0.31, "h": 0.68, "sigma8_lcdm": 0.81, "n_s": 0.965, "logfR0": 5.3}
fid_w = {"Omega_b": 0.048, "Omega_m": 0.29, "h": 0.71, "sigma8": 0.79, "n_s": 0.97, "w": -0.85}


def with_As(P, s8name, As=2.2e-9):
    Q = dict(P)
    Q.pop(s8name)
    Q["A_s"] = As
    return Q


# sigma8
for model in ("LCDM", "wCDM"):
    e = Sigma8Emulator(model, verbose=False)
    for P in (fid_fR, fid_w, dict(fid_w, Omega_m=0.18, h=0.55)):
        d = {k: P.get(k, -1.0) for k in e.params_range if k != "ln1e10As"}
        d["ln1e10As"] = np.log(2.2e-9 * 1e10)
        Q = {k: v for k, v in d.items() if k != "ln1e10As"}
        Q["A_s"] = 2.2e-9
        add("s8", model, "-", Q, 1.0, 0, 0, [], lambda d=d, e=e: e.predict_sigma8(d), "sigma8")

# f(R) boost
fr = NonLinearMGBoostEmulator("fR", verbose=False)
k = [0.005, 0.02, 0.05, 0.1, 0.3, 1.0, 3.0, 9.0]
for P, a, ek, ec in [
    (fid_fR, 0.5, True, False),                              # between nodes, low-k extrapolation
    (fid_fR, 1.0, True, False),                              # at the last node
    (fid_fR, 0.25, True, False),                             # at the first node
    (dict(fid_fR, logfR0=4.2, Omega_m=0.2), 0.7123, True, False),
    (dict(fid_fR, logfR0=6.9, sigma8_lcdm=0.95), 0.31, True, False),
    (with_As(fid_fR, "sigma8_lcdm"), 0.62, True, False),     # A_s -> sigma8_lcdm
    (dict(fid_fR, Omega_m=0.5, h=0.9), 0.8, True, True),     # clamped parameters
    (dict(fid_fR, Omega_m=0.5), 0.8, True, False),           # out of range
    (dict(fid_fR, logfR0=7.5), 0.8, True, True),             # logfR0 is never clamped
    (fid_fR, 0.8, False, False),                             # k < k0 without extrapolation
    (fid_fR, 0.2, True, False),                              # a out of range
]:
    add("fr", "fR", "-", P, a, ek, ec, k,
        lambda P=P, a=a, ek=ek, ec=ec: fr.predict_boost(P, a, k=k, extrapolate_k_low=ek, extrapolate_cosmo=ec), "sigma8_lcdm")
add("fr", "fR", "-", fid_fR, 0.5, 1, 0, [], lambda: fr.predict_boost(fid_fR, 0.5), "sigma8_lcdm")  # default bins

# wCDM boost
wc = NonLinearBoostEmulator("wCDM", verbose=False)
kw = [0.04, 0.1, 0.3, 1.0, 3.0, 9.0]
for P, a in [(fid_w, 0.5), (fid_w, 1.0), (dict(fid_w, w=-1.4, Omega_m=0.4), 0.33),
             (with_As(fid_w, "sigma8"), 0.71), (dict(fid_w, w=-1.6), 0.5)]:
    add("wc", "wCDM", "-", P, a, 0, 0, kw, lambda P=P, a=a: wc.predict_boost(P, a, k=kw), "sigma8")
add("wc", "wCDM", "-", fid_w, 0.5, 0, 0, [0.001], lambda: wc.predict_boost(fid_w, 0.5, k=[0.001]), "sigma8")

# HMF, every file, with the std
for model, P0, s8name in (("fR", fid_fR, "sigma8_lcdm"), ("wCDM", fid_w, "sigma8")):
    for md in ("200c", "500c", "1000c", "b0.2"):
        for rc in (True, False):
            h = HMFEmulator(model, md, use_resolution_correction=rc, verbose=False)
            for i, (P, a, ext) in enumerate([(P0, 0.6, False), (with_As(P0, s8name), 0.9, False), (P0, 1.0, True)]):
                mlo, mhi = h.range("mass_halo", aexp=a)
                m = list(np.geomspace(mlo * 1.01, mhi * (3.0 if ext else 0.99), 7))
                add("hmf", model, f"{md}:{int(rc)}", P, a, ext, 0, m,
                    lambda h=h, P=P, a=a, m=m, ext=ext: h.predict_hmf(m, P, a, return_std=True, extrapolate_mass_halo_high=ext),
                    s8name)
    h = HMFEmulator(model, "200c", verbose=False)
    add("hmf", model, "200c:1", P0, 0.6, 0, 0, [1e17], lambda h=h, P0=P0: h.predict_hmf([1e17], P0, 0.6), s8name)

print(f"// Generated by make_emantis_reference.py (e-MANTIS {emantis.__version__}, scikit-learn {sklearn.__version__}). Do not edit.")
print("#pragma once\n#include <cmath>\n#include <string>\n#include <vector>\n")
print("namespace EMantisReference {")
print("    struct Case {")
print("        std::string kind, model, extra;")
print("        double Omega_b, Omega_m, h, n_s, sigma8, A_s, w, logfR0, a;")
print("        int flag1, flag2;")
print("        std::vector<double> x, expected, expected_std;")
print("        std::string error; // the parameter of the EmulationRangeError, if any")
print("    };")
print("    const std::vector<Case> cases = {")
for kind, model, extra, Q, a, f1, f2, x, pred, std, err in cases:
    vals = ", ".join(repr(float(Q[k])) if np.isfinite(Q[k]) else "NAN"
                     for k in ("Omega_b", "Omega_m", "h", "n_s", "sigma8", "A_s", "w", "logfR0"))
    print(f'        {{"{kind}", "{model}", "{extra}", {vals}, {a!r}, {int(f1)}, {int(f2)}, {arr(x) if len(x) else "{}"}, '
          f'{arr(pred) if len(pred) else "{}"}, {arr(std) if len(std) else "{}"}, "{err}"}},')
print("    };")
print("}")
