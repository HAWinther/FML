#!/usr/bin/env python3
"""Regenerate the PyTorch reference values of test_neural_network.cpp (needs torch; run from this folder):

    python3 make_torch_reference.py

Writes TorchReference.h (losses, gradients and the parameters after 3 clipped Adam steps for each activation and
loss; the learning rates of ReduceLROnPlateau for a sequence of losses) and data/lightning_emulator.txt with
data/lightning_emulator_expected.txt (a network of Emulator.py's structure in a Lightning-style checkpoint, exported
with ../export_lightning_emulator.py, and its outputs evaluated by torch in double precision).
"""

import os
import subprocess
import sys
import tempfile

import torch
import torch.nn as nn
import torch.nn.functional as F

torch.set_default_dtype(torch.float64)
HERE = os.path.dirname(os.path.abspath(__file__))

ACT = {
    "identity": lambda x: x,
    "relu": F.relu,
    "tanh": torch.tanh,
    "sigmoid": torch.sigmoid,
    "gelu": F.gelu,
    "silu": F.silu,
    "elu": F.elu,
    "leaky_relu": F.leaky_relu,
    "softplus": F.softplus,
}
LOSS = {"mse": nn.MSELoss(), "l1": nn.L1Loss(), "huber": nn.HuberLoss()}


class Net(nn.Module):
    """The structure of Emulator.py's Net (the same attribute names and registration order)"""

    def __init__(self, sizes, activation):
        super().__init__()
        self.hidden_layers = nn.ModuleList()
        self.activations = nn.ModuleList()
        self.output_layer = nn.Linear(sizes[-2], sizes[-1])
        self.dropout = nn.Dropout(p=0.0)
        for i in range(len(sizes) - 2):
            self.hidden_layers.append(nn.Linear(sizes[i], sizes[i + 1]))
        self.activation = ACT[activation]

    def forward(self, x):
        for layer in self.hidden_layers:
            x = self.activation(layer(x))
        return self.output_layer(x)

    def flat(self):
        """The parameters in FML's order: per layer the weights (row-major) then the biases"""
        out = []
        for layer in list(self.hidden_layers) + [self.output_layer]:
            out += layer.weight.detach().flatten().tolist() + layer.bias.detach().tolist()
        return out

    def flat_grad(self):
        out = []
        for layer in list(self.hidden_layers) + [self.output_layer]:
            out += layer.weight.grad.flatten().tolist() + layer.bias.grad.tolist()
        return out


def arr(values):
    return "{" + ", ".join(repr(float(v)) for v in values) + "}"


def main():
    sizes = [3, 5, 4, 2]
    lr, wd, clip, steps = 1e-2, 1e-3, 0.5, 3
    cases = [(a, "mse") for a in ACT] + [("tanh", "l1"), ("tanh", "huber")]
    out = ["// Generated by make_torch_reference.py (torch " + torch.__version__ + "). Do not edit.",
           "#pragma once", "#include <string>", "#include <vector>", "", "namespace TorchReference {",
           f"    const std::vector<int> sizes = {{{', '.join(map(str, sizes))}}};",
           f"    const double lr = {lr!r}, weight_decay = {wd!r}, clip = {clip!r};",
           f"    const int adam_steps = {steps};",
           "    struct Case {", "        std::string activation, loss;",
           "        std::vector<double> params, X, Y, output, grad, params_after;", "        double loss_value;",
           "    };", "    const std::vector<Case> cases = {"]
    for n, (act, loss) in enumerate(cases):
        torch.manual_seed(100 + n)
        net = Net(sizes, act)
        with torch.no_grad():
            for p in net.parameters():
                p.copy_(0.7 * torch.randn_like(p))
        X = torch.randn(6, sizes[0])
        Y = torch.randn(6, sizes[-1])
        params = net.flat()
        output = net(X)
        value = LOSS[loss](output, Y)
        value.backward()
        grad = net.flat_grad()
        opt = torch.optim.Adam(net.parameters(), lr=lr, weight_decay=wd)
        for _ in range(steps):
            opt.zero_grad()
            LOSS[loss](net(X), Y).backward()
            torch.nn.utils.clip_grad_norm_(net.parameters(), clip)
            opt.step()
        out.append(f'        {{"{act}", "{loss}", {arr(params)}, {arr(X.flatten().tolist())}, '
                   f'{arr(Y.flatten().tolist())}, {arr(output.detach().flatten().tolist())}, {arr(grad)}, '
                   f'{arr(net.flat())}, {float(value.detach())!r}}},')
    out.append("    };")

    # ReduceLROnPlateau
    metrics = [1.0, 0.9, 0.95, 0.9, 0.9, 0.91, 0.8, 0.8, 0.8, 0.8, 0.8, 0.79999, 0.7, 0.7, 0.7, 0.7, 0.7, 0.7,
               0.7, 0.7, 0.7, 0.7, 0.7, 0.7, 0.7]
    p = nn.Parameter(torch.zeros(1))
    opt = torch.optim.SGD([p], lr=0.1)
    sched = torch.optim.lr_scheduler.ReduceLROnPlateau(opt, mode="min", factor=0.5, patience=2, min_lr=0.02)
    lrs = []
    for m in metrics:
        sched.step(m)
        lrs.append(opt.param_groups[0]["lr"])
    out += ["    // ReduceLROnPlateau(lr = 0.1, factor = 0.5, patience = 2, min_lr = 0.02)",
            f"    const std::vector<double> plateau_metrics = {arr(metrics)};",
            f"    const std::vector<double> plateau_lrs = {arr(lrs)};", "} // namespace TorchReference", ""]
    with open(os.path.join(HERE, "TorchReference.h"), "w") as f:
        f.write("\n".join(out))

    # A Lightning-style checkpoint of an Emulator.py network, exported with the script
    torch.manual_seed(7)
    net = Net([4, 16, 16, 3], "gelu")
    with tempfile.TemporaryDirectory() as run:
        os.makedirs(os.path.join(run, "checkpoints"))
        state = {k: v.float() for k, v in net.state_dict().items()}  # Lightning saves float32
        torch.save({"state_dict": state, "hyper_parameters": {"activation_function": "gelu", "hidden_layers": [16, 16]}},
                   os.path.join(run, "checkpoints", "epoch=9-step=100.ckpt"))
        os.makedirs(os.path.join(HERE, "data"), exist_ok=True)
        exported = os.path.join(HERE, "data", "lightning_emulator.txt")
        subprocess.run([sys.executable, os.path.join(HERE, "..", "export_lightning_emulator.py"), run, exported],
                       check=True)
    net.load_state_dict({k: v.double() for k, v in state.items()})  # the float32 weights, evaluated in double
    X = torch.rand(5, 4) * 2 - 1
    with torch.no_grad():
        Y = net(X)
    with open(os.path.join(HERE, "data", "lightning_emulator_expected.txt"), "w") as f:
        f.write("# x (4) then y (3) per line, y from torch in double precision\n")
        for x, y in zip(X.tolist(), Y.tolist()):
            f.write(" ".join(repr(v) for v in x + y) + "\n")


if __name__ == "__main__":
    main()
