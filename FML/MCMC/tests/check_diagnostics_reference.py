"""Optional cross-check: python check_diagnostics_reference.py --driver /path/to/driver.
Requires numpy and arviz==0.21.0; the library and native tests require neither.
"""
import argparse
import subprocess
from pathlib import Path
import numpy as np
import arviz as az

def traces():
    rng = np.random.default_rng(1771)
    for n in [8, 9, 16, 31, 128, 513, 2048]:
        x = rng.normal(size=(4, n))
        yield f"iid-{n}", x
        for rho in [.8, -.8]:
            y = x.copy()
            for j in range(1, n):
                y[:, j] += rho * y[:, j-1]
            yield f"ar-{rho}-{n}", y
    x = rng.normal(size=(4, 512))
    yield "shifted", x + np.arange(4)[:, None] * 2
    yield "scales", x * 2. ** np.arange(4)[:, None]
    yield "ties", np.round(x)
    yield "heavy-tailed", rng.standard_cauchy(size=(4, 512))
    yield "near-constant", 1e12 + np.round(x * 10) / 1024
    yield "huge", x * 1e300
    y = rng.normal(size=(4, 33)); y[:, 16] = [1e5, -1e5, 2e5, -2e5]
    yield "odd-middle", y
    for i in range(32):
        yield f"random-{i}", rng.normal(size=(2+i%4, 8+13*i))

def reference_values(x):
    return np.array([az.rhat(x), az.rhat(x, method='z_scale'), az.rhat(x, method='folded'),
                     az.ess(x, method='bulk'), az.ess(x, method='tail'),
                     az.ess(x, method='quantile', prob=.05), az.ess(x, method='quantile', prob=.95)])

def write_header(path, cases):
    selected = []
    for name, x in cases:
        if name.startswith('random-'):
            continue
        if x.shape[1] <= 31:
            selected.append((name, x))
        elif name in ['shifted', 'scales', 'ties', 'heavy-tailed', 'near-constant', 'huge', 'odd-middle']:
            selected.append((name, x if name == 'odd-middle' else x[:, :31]))
    text = '// Generated by check_diagnostics_reference.py with ArviZ 0.21.0; do not edit.\n'
    text += '#ifndef FML_DIAGNOSTICS_REFERENCE_HEADER\n#define FML_DIAGNOSTICS_REFERENCE_HEADER\n'
    text += '#include <array>\n#include <vector>\nstruct DiagnosticFixture { const char * name; std::vector<std::vector<double>> chains; std::array<double, 7> expected; };\n'
    text += 'inline std::vector<DiagnosticFixture> diagnostic_fixtures() { return {\n'
    for name, x in selected:
        values = reference_values(x)
        assert np.all(np.isfinite(values)), name
        text += '{"'+name+'", {\n'
        for row in x:
            text += '{' + ','.join(format(v, '.17g') for v in row) + '},\n'
        text += '}, {' + ','.join(format(v, '.17g') for v in values) + '}},\n'
    text += '}; }\n#endif\n'
    Path(path).write_text(text)
    print(f'Wrote {len(selected)} native reference fixtures')

def main():
    p = argparse.ArgumentParser(); p.add_argument('--driver', required=True); p.add_argument('--write-header'); args = p.parse_args()
    assert az.__version__ == '0.21.0', 'Reference version must be pinned'
    cases = list(traces())
    if args.write_header:
        write_header(args.write_header, cases)
    data = ''.join(f'{a.shape[0]} {a.shape[1]}\n' + ' '.join(map(repr, a.ravel().tolist())) + '\n' for _, a in cases)
    run = subprocess.run([args.driver], input=data, text=True, check=True, capture_output=True)
    lines = run.stdout.splitlines(); assert len(lines) == len(cases)
    worst = 0.
    for (name, x), line in zip(cases, lines):
        # Public ArviZ methods; separate z/folded Rhat makes both components testable.
        expected = reference_values(x)
        actual = np.fromstring(line, sep=' ')
        assert np.all(np.isfinite(expected)), (name, expected)
        np.testing.assert_allclose(actual, expected, rtol=2e-8, atol=2e-9, err_msg=name)
        worst = max(worst, np.max(np.abs(actual-expected) / np.maximum(1, np.abs(expected))))
    print(f'{len(cases)} datasets x 7 diagnostics match ArviZ {az.__version__}; max scaled error {worst:.3g}')
if __name__ == '__main__': main()
