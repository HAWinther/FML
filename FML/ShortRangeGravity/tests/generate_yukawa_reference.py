"""Regenerate independent 100-digit Ewald reference values (requires mpmath)."""
from pathlib import Path
import mpmath as mp

mp.mp.dps = 100
rows = []
for q in map(mp.mpf, ("0", "0.00001", "0.1", "1", "4", "10")):
    for z in map(mp.mpf, ("0.00001", "0.1", "0.5", "2", "5")):
        r = 2 * q  # rs=1, lambda=1/z
        if not q:
            e = mp.exp(-z*z)
            long_p = e/mp.sqrt(mp.pi) - z*mp.erfc(z)
            long_f = ((1-2*z*z)*e+2*mp.sqrt(mp.pi)*z**3*mp.erfc(z))/(6*mp.sqrt(mp.pi))
            short_p = short_f = 0  # Singular point-source values; not compared at r=0.
        else:
            t = 2*q*z
            a = mp.exp(-t)*mp.erfc(q-z)
            b = mp.exp(t)*mp.erfc(q+z)
            short_p = (a+b)/(2*r)
            short_f = ((1+t)*a+(1-t)*b+4*q/mp.sqrt(mp.pi)*mp.exp(-q*q-z*z))/(2*r**3)
            long_p = mp.exp(-t)/r-short_p
            long_f = (1+t)*mp.exp(-t)/r**3-short_f
        if not q:
            newton_lp=1/mp.sqrt(mp.pi)
            newton_lf=1/(6*mp.sqrt(mp.pi))
            dshort_p=dshort_f=0
        else:
            newton_lp=mp.erf(q)/r
            newton_lf=(mp.erf(q)-2*q/mp.sqrt(mp.pi)*mp.exp(-q*q))/r**3
            dshort_p=mp.erfc(q)/r-short_p
            dshort_f=(mp.erfc(q)+2*q/mp.sqrt(mp.pi)*mp.exp(-q*q))/r**3-short_f
        rows.append([q,z,long_p,long_f,short_p,short_f,newton_lp-long_p,newton_lf-long_f,dshort_p,dshort_f])
lines = ["// Generated by generate_yukawa_reference.py using mpmath at 100 decimal digits.",
         "#ifndef FML_YUKAWA_REFERENCE_HEADER", "#define FML_YUKAWA_REFERENCE_HEADER", "#include <array>",
         f"inline constexpr std::array<std::array<double,10>,{len(rows)}> yukawa_reference{{{{"]
lines += ["    {{"+", ".join(format(float(x), ".17g") for x in row)+"}}," for row in rows]
lines += ["}};", "#endif", ""]
Path(__file__).with_name("YukawaReference.h").write_text("\n".join(lines))
